"""분할 전략 비교 — `make chunk-compare` → docs/generated/chunk-comparison.md (결정론적, 집계만).

data/ 아래 PDF를 추출·머리글 정리한 뒤 fixed / structure 두 전략으로 나눠 지표를 비교한다. API 호출 없음.
"""

import logging
import math
import statistics
from collections.abc import Sequence
from pathlib import Path

from app.core.config import get_settings
from app.core.ingest.chunking import STRATEGIES, build_chunks
from app.core.ingest.clean import clean_pages
from app.core.ingest.pdf import Page, extract_pages
from evaluation.dataset import REPO_ROOT

OUTPUT = REPO_ROOT / "docs" / "generated" / "chunk-comparison.md"
HEADER = "<!-- DO NOT EDIT — generated by `make chunk-compare` from data/ (로컬 전용) -->"
TINY_CHARS = 50


def ends_mid_line(chunk_text: str, page_text: str) -> bool:
    """조각이 줄 중간에서 끝났는가 (쪽 끝이나 줄바꿈 앞에서 끝나면 False)."""
    start = page_text.find(chunk_text)
    if start < 0:
        return False
    end = start + len(chunk_text)
    return end < len(page_text) and page_text[end] != "\n"


def summarize(docs: Sequence[Sequence[Page]], *, strategy: str, max_chars: int, overlap: int) -> dict:
    lengths: list[int] = []
    with_section = tiny = mid_cut = 0
    pages = 0
    for doc in docs:
        pages += len(doc)
        text_by_page = {p.number: p.text.strip() for p in doc}
        for d in build_chunks(doc, strategy=strategy, max_chars=max_chars, overlap=overlap):
            lengths.append(len(d.text))
            with_section += d.section is not None
            tiny += len(d.text) < TINY_CHARS
            mid_cut += ends_mid_line(d.text, text_by_page[d.page])
    n = len(lengths)
    ordered = sorted(lengths)
    return {
        "docs": len(docs),
        "pages": pages,
        "chunks": n,
        "avg_chars": round(statistics.mean(lengths)) if n else 0,
        "p90_chars": ordered[max(0, math.ceil(0.9 * n) - 1)] if n else 0,
        "with_section": with_section / n if n else 0.0,
        "tiny": tiny / n if n else 0.0,
        "mid_line_cut": mid_cut / n if n else 0.0,
    }


def _pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def render(rows: dict[str, dict], *, max_chars: int, overlap: int) -> str:
    first = next(iter(rows.values()))
    corpus = (f"자료: 문서 {first['docs']}개, {first['pages']}쪽 (머리글·쪽번호 정리 후). "
              f"설정: max_chars={max_chars}, overlap={overlap} (overlap은 fixed만).")
    lines = [
        HEADER, "", "# 분할 전략 비교", "", corpus, "",
        "| 전략 | 조각 수 | 평균 길이 | p90 길이 | 섹션 라벨 | 50자 미만 | 줄 중간 끊김 |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in sorted(rows):
        r = rows[name]
        lines.append(f"| {name} | {r['chunks']} | {r['avg_chars']} | {r['p90_chars']} | "
                     f"{_pct(r['with_section'])} | {_pct(r['tiny'])} | {_pct(r['mid_line_cut'])} |")
    lines += ["", "- fixed: 쪽 안에서 max_chars 창, overlap만큼 겹침",
              "- structure: 조항 경계 → 쪽(슬라이드) 1장 = 조각 1개, 넘치면 줄 경계. 섹션 = 조항 / 슬라이드 제목"]
    return "\n".join(lines) + "\n"


def load_docs(data_dir: Path) -> list[list[Page]]:
    logging.disable(logging.CRITICAL)  # pypdf 경고 억제
    return [clean_pages(extract_pages(p)) for p in sorted(data_dir.rglob("*.pdf"))
            if not any(part.startswith(".") for part in p.relative_to(data_dir).parts)]


if __name__ == "__main__":
    settings = get_settings()
    docs = load_docs(REPO_ROOT / settings.data_dir)
    rows = {s: summarize(docs, strategy=s, max_chars=settings.chunk_max_chars, overlap=settings.chunk_overlap)
            for s in STRATEGIES}
    OUTPUT.write_text(render(rows, max_chars=settings.chunk_max_chars, overlap=settings.chunk_overlap),
                      encoding="utf-8")
    print(f"wrote {OUTPUT}")
